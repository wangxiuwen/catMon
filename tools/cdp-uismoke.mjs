const port = process.argv[2] || '9223';
const targets = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const main = targets.find(t => (t.title || '').includes('系统监视器'));
const ws = new WebSocket(main.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
const send = (m, p) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const ev = async expr => { const r = await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }); return r.exceptionDetails ? 'EXC: ' + (r.exceptionDetails.exception?.description || '').slice(0, 200) : JSON.stringify(r.result?.value); };
console.log('1 打开面板:', await ev(`(async()=>{ await window.__TAURI__.core.invoke('toggle_panel'); await new Promise(r=>setTimeout(r,400)); return document.getElementById('cpuV').textContent; })()`));
console.log('2 页眉:', await ev(`document.getElementById('metricHint').textContent`));
console.log('3 系统配置组:', await ev(`document.querySelectorAll('#sysinfo .sig').length`));
console.log('4 复制按钮:', await ev(`!!document.getElementById('btnCopyInfo')`));
console.log('5 清理页切换:', await ev(`document.getElementById('navClean').click(); !!document.getElementById('viewClean') && document.getElementById('viewClean').style.display`));
await new Promise(r => setTimeout(r, 2500));
console.log('6 清理分类数:', await ev(`document.querySelectorAll('#cleanList .cat, #cleanReg .cat').length`));
console.log('7 启动项行数:', await ev(`document.querySelectorAll('#startupBody tr').length`));
console.log('8 版本号:', await ev(`document.getElementById('ver').textContent`));
console.log('9 监控页切回:', await ev(`document.getElementById('navMon').click(); document.getElementById('cpuV').textContent`));
await ev(`window.__TAURI__.core.invoke('toggle_panel')`);
process.exit(0);
